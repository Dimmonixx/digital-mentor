def show_zones():
    st.subheader("Анатомические зоны")
    st.markdown("""
    Понимание зон — основа правильного нанесения керамики.
    Каждая зона имеет свои пропорции, оттенок и прозрачность.
    """)

    col1, col2, col3 = st.columns(3)

    with col1:
        st.markdown("### Цервикальная 1/3")
        st.markdown("""
        **Характеристики:**
        - Хрома: максимальная (3-4)
        - Прозрачность: минимальная (0-5%)
        - Value: низкий
        - Поверхность: гладкая
        
        **При работе:**
        - Дентин A3-A4 или B3-B4
        - Cervical Modifier
        - Минимум эмалевых масс
        """)

    with col2:
        st.markdown("### Средняя 1/3")
        st.markdown("""
        **Характеристики:**
        - Хрома: средняя (2-3)
        - Прозрачность: 5-15%
        - Value: средний
        - Мамелоны видны
        
        **При работе:**
        - Основной дентин
        - Мамелоновые массы
        - Переходные оттенки
        """)

    with col3:
        st.markdown("### Режущая 1/3")
        st.markdown("""
        **Характеристики:**
        - Хрома: минимальная (0-1)
        - Прозрачность: 20-40%
        - Value: высокий
        - Опал-эффект
        
        **При работе:**
        - Инцизальные массы
        - Опаловые массы OPA
        - Характеризация
        """)

    st.divider()
    st.info("💡 Золотое правило: цервикальная зона всегда теплее и темнее режущей. Нарушение этого правила делает работу неестественной.")

def show_mamelons():
    st.subheader("Мамелоны")
    st.markdown("""
    Мамелоны — анатомические выступы на режущем крае,
    характерны для молодых зубов. Создают естественный 
    вид и глубину режущей зоны.
    """)

    col1, col2 = st.columns(2)

    with col1:
        st.markdown("""
        **Что такое мамелоны:**
        
        Это три бугорка на режущем крае центральных 
        и боковых резцов. Образуются из трёх отдельных 
        долей дентина при развитии зуба.
        
        **Виды:**
        - Выраженные — молодые зубы до 25 лет
        - Умеренные — взрослые зубы 25-45 лет  
        - Сглаженные — зубы после 45 лет
        - Отсутствуют — при стираемости
        """)

    with col2:
        st.markdown("""
        **Как воссоздать в керамике:**
        
        1. Нанести дентиновую массу тремя 
           отдельными порциями в режущей зоне
        2. Между мамелонами — прозрачная масса
        3. Сверху — тонкий слой инцизальной массы
        4. Опаловая масса по всему режущему краю
        
        **Ошибки:**
        - Слишком выраженные у пожилых пациентов
        - Симметричные у всех зубов (неестественно)
        - Без межмамелонных промежутков
        """)

    st.divider()
    st.warning("⚠️ Мамелоны на боковых зубах у пациента 60+ лет — грубая эстетическая ошибка. Всегда учитывай возраст пациента.")

def show_occlusal():
    st.subheader("Окклюзионный компас")
    st.markdown("""
    Окклюзионный компас — инструмент анализа 
    окклюзионной поверхности боковых зубов.
    Помогает правильно расставить бугры и фиссуры.
    """)

    col1, col2 = st.columns(2)

    with col1:
        st.markdown("""
        **Основные направления:**
        
        🔵 **Мезиальный** — к центру зубного ряда
        
        🔴 **Дистальный** — от центра зубного ряда
        
        🟡 **Вестибулярный** — к щеке
        
        🟢 **Оральный** — к языку/нёбу
        """)

    with col2:
        st.markdown("""
        **Применение:**
        
        При моделировке окклюзионной поверхности 
        учитывай направление жевательных движений:
        
        - Рабочая сторона: латеротрузия
        - Балансирующая: медиотрузия  
        - Протрузия: передние зубы
        - Торк: наклон оси зуба
        """)

    st.divider()
    st.info("💡 Мезиальный сдвиг 0.3-0.5мм — норма для центральных резцов. Больше 1мм — патология которую нужно согласовать с врачом.")

def show_opal():
    st.subheader("Прозрачность и опал-эффект")
    st.markdown("""
    Опалесценция — одно из самых сложных 
    оптических свойств зуба для воссоздания в керамике.
    """)

    col1, col2 = st.columns(2)

    with col1:
        st.markdown("""
        **Что такое опал-эффект:**
        
        Натуральная эмаль рассеивает свет как опал —
        в проходящем свете выглядит оранжево-коричневой,
        в отражённом — голубовато-белой.
        
        **Почему это важно:**
        - Без опала работа выглядит "мёртвой"
        - Зуб кажется пластиковым
        - Нет глубины и живости
        """)

    with col2:
        st.markdown("""
        **Как создать в Noritake CZR:**
        
        1. **OPA масса** — основной опал
           Наносить в режущей трети тонким слоем
           
        2. **Incisal массы** — полупрозрачные
           IN1, IN2 для разной прозрачности
           
        3. **Характеризация** — финальный штрих
           Белые пятна (white spot), трещины эмали
           
        **Обжиг:** не перегревать — опал исчезает
        при температуре выше 930°C
        """)

    st.divider()
    st.success("✅ Тест опала: поднеси коронку к окну. В проходящем свете должен быть тёплый оранжевый оттенок. Если холодный серый — опала недостаточно.")
